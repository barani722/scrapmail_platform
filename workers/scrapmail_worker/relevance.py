def _plain(text: str) -> str:
    text = unicodedata.normalize("NFKD", text)
    return "".join(c for c in text if not unicodedata.combining(c)).lower()


class _Keyword:
    """Whole-word keyword. The plain substring test skips the regex for the many
    keywords that are not in the text at all (rating stays the same, much faster)."""

    def __init__(self, word: str) -> None:
        self.plain = _plain(word)
        self.pattern = re.compile(rf"(?<![a-z0-9]){re.escape(self.plain)}(?![a-z0-9])")

    def search(self, text: str) -> bool:
        return self.plain in text and self.pattern.search(text) is not None


def _compile(words: list[str]) -> list[tuple[str, _Keyword]]:
    unique = dict.fromkeys(words)  # a repeated word must not count twice
    return [(w, _Keyword(w)) for w in unique]


_GROUPS = {"tickets": _compile(TICKETS), "events": _compile(EVENTS), "travel": _compile(TRAVEL)}
_NOT_AGENCY = _compile(NOT_AGENCY)
_NOT_AGENCY_UNLESS = _compile(NOT_AGENCY_UNLESS_AGENCY)
_AGENCY_WORDS = _compile(AGENCY_WORDS)


@dataclass
class Relevance:
    level: str
    score: int
    keywords: list[str] = field(default_factory=list)

    @property
    def is_relevant(self) -> bool:
        """Good enough to add a discovered website as a new agency."""
        return self.level in ("A", "B", "C")


def rate(text: str, headline: str = "") -> Relevance:
    """Rate a website from its visible text and headline (title + description)."""
    body, head = _plain(text), _plain(headline)
    hits: dict[str, list[str]] = {}
    score = 0
    weights = {"tickets": 10, "events": 5, "travel": 3}
    for group, patterns in _GROUPS.items():
        found = [word for word, pattern in patterns if pattern.search(body) or pattern.search(head)]
        hits[group] = found
        # Words in the title/description count double: they describe the business.
        in_head = sum(1 for word, pattern in patterns if pattern.search(head))
        score += weights[group] * (len(found) + in_head)

    tickets, events, travel = (len(hits[g]) for g in ("tickets", "events", "travel"))
    if tickets >= 1 and events >= 2 or tickets >= 3 and events >= 1:
        level = "A"
    elif events >= 2 and (travel >= 1 or tickets >= 1):
        level = "B"
    elif travel >= 2 or (travel >= 1 and events >= 1):
        level = "C"
    elif travel or events or tickets:
        level = "D"
    else:
        level = "E"

    keywords = hits["tickets"] + hits["events"] + hits["travel"]

    # Not an agency (club, venue, software, jobs …): at most D, with the reason kept.
    hard = [word for word, pattern in _NOT_AGENCY if pattern.search(head)]
    soft = [word for word, pattern in _NOT_AGENCY_UNLESS if pattern.search(head)]
    agency = any(pattern.search(head) for _, pattern in _AGENCY_WORDS)
    reasons = hard or ([] if agency else soft)
    if reasons and level in ("A", "B", "C"):
        level = "D"
        keywords = [f"not an agency: {reasons[0]}", *keywords]

    return Relevance(level=level, score=min(score, 1000), keywords=keywords[:30])
